#pragma once
#include <windows.h>

// 压缩软件处理模块。两个用途，语义刻意分开：
//
//   1) closeAll()        —— 界面按钮「关闭压缩软件」用：把所有压缩软件一次关干净。
//   2) startGuard()      —— 后台常驻看护：只管"同一个压缩包被开出多个窗口"，
//                           一组里留最新打开的那个，其余关掉。
//
// 两者都是"礼貌关闭"而不是强杀：按 exe 名认出压缩软件，给它可见的顶层窗口发
// WM_CLOSE，让软件自己走正常退出流程（该提示保存、该问确认都由它自己问）。
// 这样即使某个软件正开着待保存的压缩包，也不会被 TerminateProcess 撕掉数据。
//
// 名单只收 GUI 主程序：7z.exe / rar.exe 这类命令行工具常被别的软件当子进程调用，
// 关掉它们等于破坏别人的工作，一律不碰。
namespace ZipKill
{
	// 扫描并关闭当前存在的全部压缩软件。返回本次真正发过关闭消息的进程数。
	int closeAll();

	// 后台看护：只处理"同一个压缩包开了多个窗口"。返回本轮关掉的窗口数。
	//
	// 分组维度是「窗口」而不是「进程」，因为 Bandizip / NanaZip 这类是单进程多窗口：
	// 按 PID 分组时 pids.size() > 1 根本不成立，逻辑永远不触发（原始设计就栽在这）。
	// 分组键 = (exe 名, 窗口标题里 " - " 之前那段)，标题通常就是压缩包名或完整路径。
	// 同一组里保留**最新打开**的那个（跨进程按进程创建时间、同进程多窗口退到
	// 首次出现的时刻，完全并列才看 z 序），其余发 WM_CLOSE。
	// 不同压缩包各开一个时不属于同一组，不会被误关。
	int dedupSameArchive();

	// 起 / 停后台看护线程。App 启动时起，退出前停（会 join）。
	void startGuard();
	void stopGuard();
}
